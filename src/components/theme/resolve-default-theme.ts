/**
 * Раздельные дефолты темы: /admin/* — тёмная (офисная работа за столом,
 * унаследованный вид админки), всё остальное — светлая (рабочие экраны на
 * телефоне, вероятно яркое цеховое освещение — см. аудит). Тумблер —
 * переопределение поверх этого дефолта: явный выбор пользователя (в
 * localStorage) побеждает везде, независимо от раздела; дефолт применяется
 * только пока явного выбора нет.
 *
 * Та же логика продублирована как строка в theme-script.ts (инлайн-скрипт
 * не может импортировать модуль) — при изменении менять оба места.
 */
export function isAdminPath(pathname: string): boolean {
  return /^\/admin(\/|$)/.test(pathname);
}

export function resolveDefaultTheme(pathname: string): "light" | "dark" {
  return isAdminPath(pathname) ? "dark" : "light";
}
